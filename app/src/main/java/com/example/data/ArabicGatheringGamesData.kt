package com.example.data

// -----------------------------------------------------------------------------
// 1. بدون كلام (CHARADES & EMOJI MOVIES / PROVERBS)
// -----------------------------------------------------------------------------
enum class BedoonKalamMode {
    EMOJI_GUESS,      // Solo: Guess from emojis
    ACTING_CHARADES   // Gathering: Secret card revealed for acting without speaking
}

data class BedoonKalamItem(
    val id: String,
    val title: String,
    val category: String, // "أفلام", "مسرحيات", "أمثال شعبية", "مسلسلات"
    val emojis: String,
    val hints: List<String>,
    val acceptableAnswers: List<String>,
    val actingTips: String
)

// -----------------------------------------------------------------------------
// 2. التابو العربي (THE FORBIDDEN WORD / TABOO)
// -----------------------------------------------------------------------------
data class TabooCard(
    val id: String,
    val mainWord: String,
    val forbiddenWords: List<String>, // 5 forbidden words
    val category: String,
    val icon: String
)

// -----------------------------------------------------------------------------
// 3. كمّل المثل الشعبي (PROVERB COMPLETION)
// -----------------------------------------------------------------------------
data class ProverbItem(
    val id: String,
    val prompt: String,      // e.g. "اللي ميعرفش يقول..."
    val correctAnswer: String, // "عدس"
    val options: List<String>, // 4 choices
    val origin: String,       // "مصري", "شامي", "خليجي", "عربي فصيح"
    val funMeaning: String
)

// -----------------------------------------------------------------------------
// 4. المليون العربي (WHO WANTS TO BE A MILLIONAIRE)
// -----------------------------------------------------------------------------
data class MillionaireQuestion(
    val level: Int,           // 1 to 15
    val prizeValue: Int,      // 100, 200, 300, 500, 1000, 2000, 4000, 8000, 16000, 32000, 64000, 125000, 250000, 500000, 1000000
    val question: String,
    val options: List<String>,// 4 options
    val correctIndex: Int,
    val audiencePercentages: List<Int>, // e.g. [70, 10, 12, 8]
    val friendTip: String
)

// -----------------------------------------------------------------------------
// 5. الرابط العجيب / أربع كلمات وكلمة (FOUR CLUES ONE WORD)
// -----------------------------------------------------------------------------
data class FourCluesItem(
    val id: String,
    val clues: List<String>, // 4 clues, e.g. ["نيل", "فرات", "دجلة", "بردى"]
    val answer: String,      // "أنهار"
    val categoryHint: String,// "جغرافيا وطبيعة"
    val icon: String
)

// -----------------------------------------------------------------------------
// 6. وضع التجمع على جهاز واحد (PASS & PLAY TEAMS)
// -----------------------------------------------------------------------------
data class GatheringTeamState(
    val teamRedName: String = "الفريق الأحمر 🔴",
    val teamBlueName: String = "الفريق الأزرق 🔵",
    val redScore: Int = 0,
    val blueScore: Int = 0,
    val currentTurnTeam: String = "RED", // "RED" or "BLUE"
    val currentRound: Int = 1,
    val totalRounds: Int = 5,
    val isGameFinished: Boolean = false
)

